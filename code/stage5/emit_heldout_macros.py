"""Emit the held-out (out-of-fine-tuning) cross-corpus numbers into the paper.

Writes figures/numbers_heldout.tex in the Speech-to-Text-Verification repo:
  * \HO<Corpus><Spec><Snr>  certified fraction, e.g. \HOUwbMsgSixty
  * \HO<Corpus>N            number of certified files for that corpus
  * \HOHeldoutTable         the full tabular body (so no number is hand-typed)
SNRs are spelled out (Sixty/Forty/Twenty) so no macro name contains a digit --
this deliberately avoids the digit-catcode machinery main.tex needs for
numbers_pi.tex, and lets this file be \input under normal catcodes.

Certified-robust <=> k <= k*(N,beta,tau) with k*=20 for N=1000, beta=1e-6, tau=0.05.
Run after the held-out campaigns finish:  python emit_heldout_macros.py
"""
import csv
from pathlib import Path
from collections import defaultdict
from scipy.stats import beta as betadist

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "Speech-to-Text-Verification" / "figures"
csv.field_size_limit(1 << 24)
N, BETA, TAU = 1000, 1e-6, 0.05
SNRS = [(60, "Sixty"), (40, "Forty"), (20, "Twenty")]


def kstar(N, b, tau):
    k = 0
    while k <= N and betadist.ppf(1 - b, k + 1, N - k) <= tau:
        k += 1
    return k - 1


KSTAR = kstar(N, BETA, TAU)

# macroname, printed label, csv, condition, site (airport/source), region, in-training
CORPORA = [
    ("Atcosim", "ATCOSIM",  "results_atc_whisper_atc_atcosim.csv",     "clean",
     "simulation", "Europe", True),
    ("Atcotwo", "ATCO2",    "results_atc_whisper_atc_atco2.csv",       "noisy",
     "multiple feeds", "Europe", True),
    ("Uwb",     "UWB-ATCC", "results_atc_whisper_atc_heldout_uwb.csv", "noisy",
     "Czech ANS", "Europe", False),
    ("Poland",  "Poland",   "results_atc_whisper_atc_heldout_eu.csv",  "noisy",
     "Krak\\'ow (EPKK)", "Europe", False),
    ("Nl",      "Netherlands", "results_atc_whisper_atc_heldout_nl.csv", "noisy",
     "Amsterdam (EHAM)", "Europe", False),
    ("No",      "Norway",   "results_atc_whisper_atc_heldout_no.csv",  "noisy",
     "Trondheim (ENVA)", "Europe", False),
    ("Se",      "Sweden",   "results_atc_whisper_atc_heldout_se.csv",  "noisy",
     "G\\\"oteborg (ESGG)", "Europe", False),
    ("Ca",      "Canada",   "results_atc_whisper_atc_heldout_ca.csv",  "noisy",
     "Calgary (CYYC)", "N.\\,America", False),
    ("Us",      "United States", "results_atc_whisper_atc_heldout.csv", "noisy",
     "Boston (KBOS)", "N.\\,America", False),
]


def load(fn):
    """Return (per-SNR aggregate, msg SNR-budget fraction certified at ALL scanned SNRs)."""
    agg = defaultdict(lambda: [0, 0, 0])
    per = defaultdict(dict)
    p = HERE / fn
    if not p.exists():
        return None, None
    for r in csv.DictReader(open(p, newline="")):
        try:
            if int(r["N"]) != N:
                continue
            snr, km, kc = int(r["snr"]), int(r["k_msg"]), int(r["k_cs"])
        except (TypeError, ValueError, KeyError):
            continue
        a = agg[snr]
        a[0] += 1
        a[1] += (km <= KSTAR)
        a[2] += (kc <= KSTAR)
        per[r["file"]][snr] = km
    snrs = [s for s, _ in SNRS]
    budget = (sum(1 for d in per.values() if all(d.get(s, 10 ** 9) <= KSTAR for s in snrs))
              / len(per)) if per else float("nan")
    return agg, budget


def main():
    L = ["% auto-generated by Stage-5-atc/emit_heldout_macros.py -- do not edit",
         f"% certified-robust <=> k <= {KSTAR} (N={N}, beta={BETA}, tau={TAU})",
         f"\\newcommand{{\\HOKstar}}{{{KSTAR}}}",
         f"\\newcommand{{\\HONdraws}}{{{N}}}"]
    rows, missing = [], []
    for mac, label, fn, cond, site, reg, intrain in CORPORA:
        agg, budget = load(fn)
        if agg is None or not any(agg[s][0] for s, _ in SNRS):
            missing.append(label)
            continue
        n = max(agg[s][0] for s, _ in SNRS)
        L.append(f"\\newcommand{{\\HO{mac}N}}{{{n}}}")
        L.append(f"\\newcommand{{\\HO{mac}Budget}}{{{budget:.2f}}}")
        cells = []
        for s, word in SNRS:
            cnt, cm, cc = agg[s]
            fm = cm / cnt if cnt else float("nan")
            fc = cc / cnt if cnt else float("nan")
            L.append(f"\\newcommand{{\\HO{mac}Msg{word}}}{{{fm:.2f}}}")
            L.append(f"\\newcommand{{\\HO{mac}Cs{word}}}{{{fc:.2f}}}")
            cells.append(f"{fm:.2f} & {fc:.2f}")
        # NOTE: the in-fine-tuning flag and the SNR-budget column are deliberately
        # not printed -- membership is conveyed by the rule splitting the table,
        # and the budget figures are quoted in the text via \HO<Corpus>Budget.
        rows.append(f"{label} & {cond} & {site} & {reg} & {n} & "
                    + " & ".join(cells) + " \\\\")

    tbl = ["\\newcommand{\\HOHeldoutTable}{%",
           "\\begin{tabular}{lllcr" + "cc" * len(SNRS) + "}",
           "\\toprule",
           "& & & & & \\multicolumn{2}{c}{60\\,dB} & \\multicolumn{2}{c}{40\\,dB} & "
           "\\multicolumn{2}{c}{20\\,dB} \\\\",
           "\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\\cmidrule(lr){10-11}",
           "dataset & condition & site & region & $n$ & msg & cs & msg & cs "
           "& msg & cs \\\\",
           "\\midrule"]
    # in-fine-tuning corpora first, then a rule, then the disjoint held-out sets
    n_in = sum(1 for c in CORPORA if c[6])   # c[6] = in-fine-tuning flag
    tbl += rows[:n_in] + ["\\midrule"] + rows[n_in:]
    tbl += ["\\bottomrule", "\\end{tabular}}"]
    L += tbl

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "numbers_heldout.tex").write_text("\n".join(L) + "\n")
    print(f"wrote {OUT / 'numbers_heldout.tex'}  ({len(rows)} corpora, k*={KSTAR})")
    if missing:
        print("  MISSING (not yet run):", ", ".join(missing))


if __name__ == "__main__":
    main()
