"""LaTeX macros for the TMLR revision's new analyses -> figures_rev/numbers_revision.tex

Sources (all in Stage-5-atc/):
  zeronoise_summary.json   analyze_zeronoise.py      zero-noise control
  callsign_validation.json validate_callsign.py      extractor vs ATCO2 gold tags
  traffic_context.json     analyze_traffic_context.py  flips vs surveillance lists
  inherent_snr.json        estimate_inherent_snr.py  recording SNR, total SNR
  probe_digits_<m>.csv     probe_digits.py           numerals in clean decodes

Macro names are letters-only.  A value whose source is not (yet) available is
emitted as a visible red placeholder, so the manuscript always compiles and
pending numbers cannot pass unnoticed.

Run:  python emit_revision_macros.py
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "Speech-to-Text-Verification" / "figures_rev"
ML = {"quartznet": "Q", "deepspeech2": "D", "whisper": "W", "whisper_atc": "F"}
DL = {"atcosim": "A", "atco2": "O"}
PENDING = r"\textcolor{red}{\textbf{[pending]}}"


def load(name):
    p = HERE / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(a, b, nd=1):
    return f"{100 * a / b:.{nd}f}" if b else None


def main():
    L = ["% generated by RadioStar/Stage-5-atc/emit_revision_macros.py -- do not edit"]
    seen = set()

    def mac(name, val):
        seen.add(name)
        if isinstance(val, int):
            val = f"{val:,}"
        L.append(f"\\newcommand{{\\{name}}}{{{PENDING if val is None else val}}}")

    # ---- zero-noise control -------------------------------------------------
    zn = load("zeronoise_summary.json") or []
    full = {"atcosim": 1500, "atco2": 857}
    idx = {(r["model"], r["dataset"], r["config"]): r for r in zn}
    for m, ms in ML.items():
        for d, ds in DL.items():
            for cfg, cs in (("campaign", ""), ("notf32", "NoTF")):
                if m in ("whisper", "whisper_atc") and cfg == "notf32":
                    continue
                r = idx.get((m, d, cfg))
                done = r is not None and r["n_msgs"] >= full[d]
                g = (lambda k: r[k]) if done else (lambda k: None)
                p = f"Zn{ms}{ds}{cs}"
                mac(p + "N", g("n_msgs"))
                mac(p + "Nzero", g("N0"))
                mac(p + "Any", g("any_k0_raw"))
                mac(p + "AnyPct", pct(r["any_k0_raw"], r["n_msgs"]) if done else None)
                mac(p + "FailMsg", g("fail_k0_msg_old"))
                mac(p + "FailCs", g("fail_k0_cs_old"))
                mac(p + "FailMsgNew", g("fail_k0_msg_new"))
                mac(p + "Mixed", g("mixed_diff"))
                mac(p + "BoneRep", g("b1_repeat_diff"))
                mac(p + "NotcertMsg", g("camp60_msg_notcert"))
                mac(p + "NotcertMsgZero", g("camp60_msg_notcert_zero_fail"))
                mac(p + "NotcertMsgZeroPct",
                    pct(r["camp60_msg_notcert_zero_fail"], r["camp60_msg_notcert"])
                    if done else None)
                mac(p + "NotcertCs", g("camp60_cs_notcert"))
                mac(p + "NotcertCsZero", g("camp60_cs_notcert_zero_fail"))
                mac(p + "NotcertCsZeroPct",
                    pct(r["camp60_cs_notcert_zero_fail"], r["camp60_cs_notcert"])
                    if done else None)
    # campaign-wide totals over the CTC models
    ctc = [idx.get((m, d, "campaign")) for m in ("quartznet", "deepspeech2")
           for d in DL]
    if all(r is not None and r["n_msgs"] >= full[r["dataset"]] for r in ctc):
        mac("ZnCtcAny", sum(r["any_k0_raw"] for r in ctc))
        mac("ZnCtcMsgs", sum(r["n_msgs"] for r in ctc))
    else:
        mac("ZnCtcAny", None); mac("ZnCtcMsgs", None)
    nt = [idx.get((m, d, "notf32")) for m in ("quartznet", "deepspeech2")
          for d in DL]
    if all(r is not None and r["n_msgs"] >= full[r["dataset"]] for r in nt):
        mac("ZnCtcNoTFAny", sum(r["any_k0_raw"] for r in nt))
    else:
        mac("ZnCtcNoTFAny", None)

    # ---- call-sign extractor validation ---------------------------------------
    cv = load("callsign_validation.json")
    if cv:
        h, g = cv["heuristic"], cv["grammar"]
        P = lambda x: f"{100 * x:.1f}"
        for k, v in [("CvNtagged", cv["n_tagged"]), ("CvNgold", cv["n_gold"]),
                     ("CvNnogold", cv["n_nogold"]),
                     ("CvGoldInit", cv["gold_initial"]),
                     ("CvGoldNoninit", cv["gold_noninitial"]),
                     ("CvRecordings", cv["recordings"]),
                     ("CvUnmatched", cv["unmatched"]),
                     ("CvSionN", cv["airports"].get("LSGS", 0)),
                     ("CvHeurSig", P(h["signature"])),
                     ("CvHeurSigInit", P(h["sig_initial"])),
                     ("CvHeurSigNoninit", P(h["sig_noninitial"])),
                     ("CvHeurExact", P(h["exact"])),
                     ("CvHeurExactInit", P(h["exact_initial"])),
                     ("CvHeurCovers", P(h["covers"])),
                     ("CvHeurSuperset", h["superset"]),
                     ("CvHeurTrunc", h["truncated"]),
                     ("CvHeurNogoldNonempty", P(h["nogold_nonempty"])),
                     ("CvHeurNogoldEmpty", P(1 - h["nogold_nonempty"])),
                     ("CvGramSig", P(g["signature"])),
                     ("CvGramSigInit", P(g["sig_initial"])),
                     ("CvGramSigNoninit", P(g["sig_noninitial"])),
                     ("CvGramExact", P(g["exact"])),
                     ("CvGramCovers", P(g["covers"])),
                     ("CvGramFound", P(g["found"])),
                     ("CvGramNogoldEmpty", P(g["nogold_empty"]))]:
            mac(k, v)
        mac("CvAirports", len(cv["airports"]))
        mac("CvSionPct", pct(cv["airports"].get("LSGS", 0), cv["n_tagged"], 0))

    # ---- traffic context ------------------------------------------------------
    tc = load("traffic_context.json")
    if tc:
        for m, ms in ML.items():
            r = tc.get(m)
            ok = r is not None and (m != "whisper" or r["source"] == "v2"
                                    and r["clean"]["files"] >= 853)
            g = (lambda k: r[k]) if ok else (lambda k: None)
            mac(f"Tc{ms}HasId", r["clean"]["has_id"] if ok else None)
            mac(f"Tc{ms}Listed", r["clean"]["id_listed"] if ok else None)
            mac(f"Tc{ms}IdChanged", g("listed_identity_changed"))
            ls = r.get("listed_subset", {}) if ok else {}
            mac(f"Tc{ms}OtherListed", ls.get("other_listed", 0) if ok else None)
            mac(f"Tc{ms}Unlisted", ls.get("unlisted", 0) if ok else None)
            mac(f"Tc{ms}Lost", ls.get("lost", 0) if ok else None)
            for k, n in (("listed_frac_lost", "LostPct"),
                         ("listed_frac_flip", "FlipPct"),
                         ("listed_frac_flips_other_listed", "OtherListedPct"),
                         ("frac_flips_other_listed", "OtherListedAllPct")):
                v = r.get(k) if ok else None
                mac(f"Tc{ms}{n}", f"{100 * v:.1f}" if v is not None else None)
            hc = r.get("heuristic_cs_flip_draws") if ok else None
            hs = r.get("heuristic_cs_flip_identity_same_draws") if ok else None
            mac(f"Tc{ms}HeurSameIdPct", pct(hs, hc) if ok and hc else None)
        sizes = tc.get("_traffic_list_sizes", {})
        tot = sum(sizes.values())
        if tot:
            acc, med = 0, None
            for s, c in sorted(((int(k), v) for k, v in sizes.items())):
                acc += c
                if med is None and acc >= tot / 2:
                    med = s
            mac("TcListMedian", med)
            mac("TcRecordings", tot)
            mac("TcRecordingsEmpty", sizes.get("0", 0))

    # ---- inherent / total SNR -------------------------------------------------
    sn = load("inherent_snr.json")
    if sn:
        for d, ds in DL.items():
            r = sn[d]
            mac(f"Snr{ds}InhMed", f"{r['inherent_snr_db']['p50']:.1f}")
            mac(f"Snr{ds}InhLo", f"{r['inherent_snr_db']['p10']:.1f}")
            mac(f"Snr{ds}InhHi", f"{r['inherent_snr_db']['p90']:.1f}")
            mac(f"Snr{ds}Clipped", r["clipped_peak_ge_0_99"])
            mac(f"Snr{ds}ActiveMed", f"{r['active_frac']['p50']:.2f}")
            for s, w in (("60", "Sixty"), ("40", "Forty"), ("30", "Thirty"),
                         ("20", "Twenty")):
                mac(f"Snr{ds}Tot{w}", f"{r['total_snr_db'][s]['p50']:.1f}")

    # ---- zero-noise totals per Whisper model; TF32 effect on QuartzNet ---------
    for m, ms in (("whisper", "W"), ("whisper_atc", "F")):
        rows = [idx.get((m, d, "campaign")) for d in DL]
        ok = all(r is not None and r["n_msgs"] >= full[r["dataset"]] for r in rows)
        mac(f"Zn{ms}Any", sum(r["any_k0_raw"] for r in rows) if ok else None)
    mac("ZnMsgs", sum(full.values()))
    qi = load("quick_qn_impact.json")
    if qi:
        shift = max(abs(v[f"cert_{sp}_tf32"] - v[f"cert_{sp}_notf32"])
                    for v in qi.values() for sp in ("msg", "cs"))
        mac("QnTfShift", f"{100 * shift:.1f}")
    else:
        mac("QnTfShift", None)

    # ---- cross-pass drift, DeepSpeech2 + Whisper-ATC (crosspass_stats.py) -------
    xp = load("crosspass_stats.json")
    mac("XpCells", xp["cells"] if xp else None)
    mac("XpChangedPct", f"{xp['changed_pct']:.1f}" if xp else None)
    mac("XpPninetynine", xp["p99"] if xp else None)
    mac("XpMax", xp["max"] if xp else None)
    mac("XpFlips", xp["flips"] if xp else None)
    mac("XpFlipsPct", f"{xp['flips_pct']:.2f}" if xp else None)

    # ---- numerals in clean decodes ---------------------------------------------
    for m, ms in (("wh", "W"), ("whatc", "F")):
        p = HERE / f"probe_digits_{m}.csv"
        rows = list(csv.DictReader(open(p, encoding="utf-8"))) if p.exists() else []
        for d, ds in DL.items():
            r = [x for x in rows if x["dataset"] == d]
            ok = len(r) >= full[d]
            k = sum(int(x["has_digit"]) for x in r)
            mac(f"Dg{ms}{ds}", k if ok else None)
            mac(f"Dg{ms}{ds}N", len(r) if ok else None)
            mac(f"Dg{ms}{ds}Pct", pct(k, len(r)) if ok else None)

    OUT.mkdir(exist_ok=True)
    (OUT / "numbers_revision.tex").write_text("\n".join(L) + "\n",
                                              encoding="utf-8")
    pend = sum(PENDING in l for l in L)
    print(f"wrote {OUT / 'numbers_revision.tex'}: {len(seen)} macros, "
          f"{pend} pending")


if __name__ == "__main__":
    main()
