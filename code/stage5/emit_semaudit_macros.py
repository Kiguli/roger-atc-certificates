"""Emit LaTeX macros from the cosine-oracle audit (numbers_semaudit.json +
semaudit_summary.csv + semaudit_perinput.csv) into the paper repo.

Macros (model letter Q/D/W/F, corpus letter A/O):
  \SaFlips<m><d>       total call-sign-flipping draws in the campaign cell
  \SaCondNinety<m><d>  share of those flips with cosine >= 0.90 (as %)
  \SaCondNinetyFive<m><d>  ... >= 0.95 (as %)
  \SaExamples          number of floor-0.95-passing flip records collected
  \SaExamplesReleased  entries in the released semaudit_examples.json
  \SaMaxCos            highest cosine among call-sign-flipping transcripts
  \SaRawGapAll/-Max    share of raw flips that are orthography-only (%%)
  \SaFlipRatioA        min CTC-vs-Whisper-ATC flip-volume ratio, ATCOSIM

ATC_DATA_DIR=<dir>: inputs from <dir>, numbers_semaudit.tex to <dir>/figures.
Revision mode (ATC_REV=1) changes / adds:
  \SaDigFlips*, \SaDigCondNinetyFive*, \SaDigPassNinetyFive*  now count the
      ORDERED canonical digit+NATO signature flips (sigflips_* keys of
      numbers_witness.json); the campaign's digit-only counts move to
      \SaDigOnlyFlips*, \SaDigOnlyCondNinetyFive*, \SaDigOnlyPassNinetyFive*
  \SaEmb...<E>  multi-embedder audit (embedder_audit.json, audit_embedders.py),
      E in {Mini, Mpnet, Bge}: ForgiveNinety/ForgiveNinetyFive (% of all
      changed draws with cos >= floor), CondNinety/CondNinetyFive (% of
      call-sign flips passing), SigCondNinety/SigCondNinetyFive (% of signature
      flips passing), MatchedFloor (floor forgiving the same share of changed
      draws as MiniLM at 0.95), MatchedForgive, MatchedCond, MatchedSigCond;
      \SaEmbMatchedShare = MiniLM's forgiven share at 0.95 (the target).

Run after analyze_atc_semaudit.py:  python emit_semaudit_macros.py
"""
import csv
import json
from pathlib import Path

from atc_paths import DATA, FIGS, REV

HERE = DATA                    # inputs: Stage-5-atc/ unless ATC_DATA_DIR
OUT = FIGS                     # default: the paper repo's figures/
EMB_TAG = {"minilm": "Mini", "mpnet": "Mpnet", "bge": "Bge"}


def embedder_macros(L):
    """\\SaEmb* macros from embedder_audit.json (revision mode)."""
    p = DATA / "embedder_audit.json"
    if not p.exists():
        return
    ea = json.loads(p.read_text())
    ref = ea["reference"]
    L.append(f"\\newcommand{{\\SaEmbMatchedShare}}"
             f"{{{100*ref['forgive_share']:.1f}}}")
    for e, et in EMB_TAG.items():
        d = ea["pooled"].get(e)
        if not d:
            continue
        for key, tag in (("forgive90", "ForgiveNinety"),
                         ("forgive95", "ForgiveNinetyFive"),
                         ("cs_pass90", "CondNinety"),
                         ("cs_pass95", "CondNinetyFive"),
                         ("sig_pass90", "SigCondNinety"),
                         ("sig_pass95", "SigCondNinetyFive"),
                         ("matched_forgive", "MatchedForgive"),
                         ("cs_pass_matched", "MatchedCond"),
                         ("sig_pass_matched", "MatchedSigCond")):
            if d.get(key) is not None:
                L.append(f"\\newcommand{{\\SaEmb{tag}{et}}}"
                         f"{{{100*d[key]:.1f}}}")
        if d.get("matched_floor") is not None:
            L.append(f"\\newcommand{{\\SaEmbMatchedFloor{et}}}"
                     f"{{{d['matched_floor']:.3f}}}")


ML = {"quartznet": "Q", "deepspeech2": "D", "whisper": "W",
      "whisper_atc": "F"}
DL = {"atcosim": "A", "atco2": "O"}


def main():
    nums = json.loads((HERE / "numbers_semaudit.json").read_text())
    ex = json.loads((HERE / "semaudit_examples.json").read_text())
    L = ["% AUTO-GENERATED by emit_semaudit_macros.py -- do not edit"]
    for m, ms in ML.items():
        for ds, dsl in DL.items():
            fl = nums.get(f"csflips_{m}_{ds}")
            if fl is None:
                continue
            L.append(f"\\newcommand{{\\SaFlips{ms}{dsl}}}{{{fl:,}}}")
            for tag, key in (("CondNinety", f"condpass90_{m}_{ds}"),
                             ("CondNinetyFive", f"condpass95_{m}_{ds}")):
                v = nums.get(key)
                if v is not None:
                    L.append(f"\\newcommand{{\\Sa{tag}{ms}{dsl}}}"
                             f"{{{100*v:.1f}}}")
    L.append(f"\\newcommand{{\\SaExamples}}{{{nums['examples_pass95']:,}}}")
    L.append(f"\\newcommand{{\\SaExamplesReleased}}{{{len(ex)}}}")
    if ex:
        L.append(f"\\newcommand{{\\SaMaxCos}}{{{ex[0]['cos']:.3f}}}")
    # raw-vs-normalized flip gap: share of raw flipping draws that are
    # orthography-only artifacts (re-tokenization), pooled and per-cell max
    raws = {(m, ds): nums.get(f"csflips_raw_{m}_{ds}")
            for m in ML for ds in DL}
    if all(v for v in raws.values()):
        raw_tot = sum(raws.values())
        norm_tot = sum(nums[f"csflips_{m}_{ds}"] for m in ML for ds in DL)
        L.append(f"\\newcommand{{\\SaRawGapAll}}"
                 f"{{{100*(raw_tot-norm_tot)/raw_tot:.1f}}}")
        gmax = max((raws[(m, ds)] - nums[f"csflips_{m}_{ds}"]) / raws[(m, ds)]
                   for m in ML for ds in DL)
        L.append(f"\\newcommand{{\\SaRawGapMax}}{{{100*gmax:.1f}}}")
    # flip-volume ratio, ATCOSIM: min over the CTC models vs Whisper-ATC
    fa = nums.get("csflips_whisper_atc_atcosim")
    ctc = [nums.get(f"csflips_{m}_atcosim") for m in ("quartznet",
                                                      "deepspeech2")]
    if fa and all(ctc):
        L.append(f"\\newcommand{{\\SaFlipRatioA}}{{{int(min(ctc)/fa)}}}")
    # digit-level flip class (scan_semaudit_witnesses.py), if available
    wp = HERE / "numbers_witness.json"
    # (revision mode: \SaDig* = ordered digit+NATO signature flips, the
    #  campaign's digit-only class as \SaDigOnly*)
    variants = ((("sig", "Dig"), ("dig", "DigOnly")) if REV
                else (("dig", "Dig"),))
    if wp.exists():
        wn = json.loads(wp.read_text())
        for kp, mt in variants:
            for m, ms in ML.items():
                for ds, dsl in DL.items():
                    fl = wn.get(f"{kp}flips_{m}_{ds}")
                    if fl is None:
                        continue
                    L.append(f"\\newcommand{{\\Sa{mt}Flips{ms}{dsl}}}{{{fl:,}}}")
                    p95 = wn.get(f"{kp}pass95_{m}_{ds}")
                    # conditional rate straight from the counts (the stored
                    # digcond95 field is pre-rounded; re-rounding it once more
                    # can be off by one ulp in the last printed digit)
                    if p95 is not None and fl:
                        L.append(f"\\newcommand{{\\Sa{mt}CondNinetyFive{ms}{dsl}}}"
                                 f"{{{100*p95/fl:.1f}}}")
                    else:
                        c95 = wn.get(f"{kp}cond95_{m}_{ds}")
                        if c95 is not None:
                            L.append(
                                f"\\newcommand{{\\Sa{mt}CondNinetyFive{ms}{dsl}}}"
                                f"{{{100*c95:.1f}}}")
                    if p95 is not None:
                        L.append(f"\\newcommand{{\\Sa{mt}PassNinetyFive{ms}{dsl}}}"
                                 f"{{{p95:,}}}")
            dt = sum(wn.get(f"{kp}flips_{m}_{ds}") or 0
                     for m in ML for ds in DL)
            dp = sum(wn.get(f"{kp}pass95_{m}_{ds}") or 0
                     for m in ML for ds in DL)
            if dt:
                L.append(f"\\newcommand{{\\Sa{mt}FlipsAll}}{{{dt:,}}}")
                L.append(f"\\newcommand{{\\Sa{mt}CondNinetyFiveAll}}"
                         f"{{{100*dp/dt:.1f}}}")
    # campaign-wide pooled rates
    tot = f90 = f95 = 0
    for r in csv.DictReader(open(HERE / "semaudit_summary.csv", newline="")):
        tot += int(r["k_csflip"])
        f90 += int(r["k_pass90"])
        f95 += int(r["k_pass95"])
    if tot:
        L.append(f"\\newcommand{{\\SaFlipsAll}}{{{tot:,}}}")
        L.append(f"\\newcommand{{\\SaCondNinetyAll}}{{{100*f90/tot:.1f}}}")
        L.append(f"\\newcommand{{\\SaCondNinetyFiveAll}}{{{100*f95/tot:.1f}}}")
    if REV:
        embedder_macros(L)
    (OUT / "numbers_semaudit.tex").write_text("\n".join(L) + "\n")
    print(f"wrote numbers_semaudit.tex ({len(L)-1} macros)")


if __name__ == "__main__":
    main()
